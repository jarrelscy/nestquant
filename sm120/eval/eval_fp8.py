        md+=['','Scheduler traffic (sum over NQ layers; bytes = rec_bytes x tp per upgrade, GB/s at 111 tok/s)','',
             '| stream | order | cap GB/s | upgrades | ups /1k tok /layer | MB/token | GB/s @111 | deferred steps | big steps | GBDT late waits |','|---|---|---|---|---|---|---|---|---|---|']
