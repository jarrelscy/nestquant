"""C2: served NestQuant (and ARVQ) routed experts scored against the FP8 reference -- one command, rerunnable.

Protocol = thread 18 (threads/18-e2e-eval/nq_e2e.py): FP8 checkpoint dequantised to bf16, bf16 math, fp32 lm_head;
teacher-forced, non-overlapping SEQ=2048 windows (== index_topk, so DSA keeps every causal key and the indexer is
skipped exactly); layer-streamed (each decoder layer is read once and applied to every stream). Only the routed experts
differ between streams; attention, dense MLPs (L0-2), shared experts, router, norms, embeddings and lm_head are FP8.

Streams (separate residual streams, each with its own routing):
  ref    FP8 experts                        all2   NQ, every expert level 2        all4  NQ, every expert level 4
  fixed  NQ, fixed set at level 4 (serving NQ_STREAM=0)
  dyn    NQ production streaming: fixed set + scheduler.Scheduler floating set, emulated per layer on the dyn stream's
         own routing (causal: a step's levels are fixed before its counts are seen; upgrades land one step later;
         serving defaults: 51 floating, EMA 512, refresh 64, 56 slots/layer, 6 GB/s at 111 tok/s split evenly over the
         75 layers, floating_default preloaded; windows chained in corpus order like one long session)
  arvq   the ARVQ hybrid checkpoint (hot NVFP4 + cold ARVQ) the box serves today (weights only, see arvqeff.py)
  aqlm   the AQLM hybrid checkpoint (prod glm-5.3: hot donor NVFP4 + cold 2-bit AQLM 1x16/g8; weights only, aqlmeff.py)
NQ weights come from the serving repack (nqeff.py: the bytes the kernel reads), so a new artifact needs only a repack.

Layout: torchrun, WORLD GPUs (4). Windows are owned w[r::WORLD] (attention, router, shared experts, head on the owner);
routed experts are expert-parallel (rank r owns experts e % WORLD == r, all TP slices): per MoE layer and stream the
normalised inputs + top-8 are all-gathered, each rank applies its experts to every token routed to them, and the fp32
partial outputs are reduce-scattered back to the owners.

  torchrun --nproc_per_node 4 eval_fp8.py --repack DIR --artifact HF_DIR [--arvq DIR] [--out DIR] [--tag T]
      [--streams all2,all4,fixed,dyn,arvq] [--n-layers N] [--windows id=32,wikitext=16,code=16] [--seed 0]
Corpora are built on first use (seeded, frozen into OUT/corpora/*.npy + manifest.json; later runs reuse them):
  id        in-distribution substitute: tb2.1 terminus-2 agent trajectories generated by GLM-5.3-Flash NVFP4 (neither
            candidate), rendered with the GLM-5.3 chat template; <= 2 windows per trajectory (the thread-18 corpora are
            not on this box)
  wikitext  OOD prose: wikitext-2 test          code  OOD code: this repo's python (written after the model cutoff)
Output: OUT/results/TAG.json (+ .md tables): per stream x corpus KLD(ref||cand) mean / stderr / p50 / p90 / p99, top-1
agreement, ppl; per layer residual divergence, router agreement, routed-output error, weight error per level / kind;
bits per expert (resident and routed-slot weighted); floating-set accuracy vs hindsight oracles; artifact version +
per-layer hashes. Env: NQ_FP8 (FP8 dir), NQ_VRAM_GB (per-process cap), NQ_SEQ."""
